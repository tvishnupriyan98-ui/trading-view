function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const TIMEFRAME_SECONDS: Record<Timeframe, number> = {
  '1m': 60,
  '5m': 300,
  '15m': 900,
  '1H': 3600,
  '4H': 14400,
  '1D': 86400,
  '1W': 604800,
};

/**
 * Generates deterministic, realistic OHLCV candlestick history ending cleanly at the symbol's current price.
 */
export function generateCandles(
  sym: MarketSymbol,
  timeframe: Timeframe = '1D',
  count = 160,
): Candle[] {
  const tfIndex = Object.keys(TIMEFRAME_SECONDS).indexOf(timeframe) + 1;
  const rng = mulberry32(sym.seed * 997 + tfIndex * 131);
  const stepSec = TIMEFRAME_SECONDS[timeframe];
  const tfScale = Math.sqrt(stepSec / 86400);
  const vol = Math.max(0.0012, sym.volatility * tfScale);

  // Anchor to deterministic reference timestamp so snapshots are stable
  const endTs = 1795305600;
  const rawCloses: number[] = [100];

  const dir = sym.changePercent >= 0 ? 1 : -1;
  const driftBias = dir * 0.00055;
  const momentumStrength = Math.min(2.4, Math.max(0.45, Math.abs(sym.changePercent) / 1.4));
  for (let i = 1; i < count; i++) {
    const progress = i / (count - 1);
    const wave = Math.sin(i / 14 + sym.seed) * vol * 0.32;
    const recentTrend = progress > 0.68 ? dir * vol * 0.34 * momentumStrength : 0;
    const shock = (rng() - 0.495) * 1.95 * vol;
    const prev = rawCloses[i - 1];
    const next = Math.max(1, prev * (1 + driftBias + wave + recentTrend + shock));
    rawCloses.push(next);
  }

  // Rescale entire series so the final close matches sym.price accurately
  const scale = sym.price / rawCloses[rawCloses.length - 1];
  const candles: Candle[] = [];

  for (let i = 0; i < count; i++) {
    const close = rawCloses[i] * scale;
    const open = i === 0 ? close * (1 - driftBias * 2) : candles[i - 1].close;
    const bodyHigh = Math.max(open, close);
    const bodyLow = Math.min(open, close);
    const wickUp = rng() * vol * 0.9 * bodyHigh;
    const wickDown = rng() * vol * 0.9 * bodyLow;
    const high = bodyHigh + wickUp;
    const low = Math.max(0.0001, bodyLow - wickDown);
    const baseVol = (sym.volume / 80) * (0.45 + rng() * 1.35);

    candles.push({
      time: endTs - (count - 1 - i) * stepSec,
      open: roundPrice(open, sym.price),
      high: roundPrice(high, sym.price),
      low: roundPrice(low, sym.price),
      close: roundPrice(close, sym.price),
      volume: Math.round(baseVol),
    });
  }

  return candles;
}

export function roundPrice(value: number, refPrice: number): number {
  const decimals = refPrice >= 1000 ? 2 : refPrice >= 10 ? 2 : 4;
  const factor = 10 ** decimals;
  return Math.round(value * factor) / factor;
}

export function formatPrice(value: number, refPrice = value): string {
  const decimals = refPrice >= 1000 ? 2 : refPrice >= 10 ? 2 : 4;
  return value.toLocaleString('en-IN', {
    minimumFractionDigits: decimals,
    maximumFractionDigits: decimals,
  });
}

export function formatVolume(vol: number): string {
  if (vol >= 1_000_000_000) return `${(vol / 1_000_000_000).toFixed(2)}B`;
  if (vol >= 1_000_000) return `${(vol / 1_000_000).toFixed(2)}M`;
  if (vol >= 1_000) return `${(vol / 1_000).toFixed(1)}K`;
  return String(vol);
}

export function applyLiveTick(lastCandle: Candle, sym: MarketSymbol): Candle {
  const deltaRatio = (Math.random() - 0.492) * sym.volatility * 0.25;
  const nextClose = roundPrice(Math.max(0.0001, lastCandle.close * (1 + deltaRatio)), sym.price);
  return {
    ...lastCandle,
    close: nextClose,
    high: Math.max(lastCandle.high, nextClose),
    low: Math.min(lastCandle.low, nextClose),
    volume: lastCandle.volume + Math.round(Math.random() * 1800 + 200),
  };
}
